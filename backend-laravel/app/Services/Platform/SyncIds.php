<?php

namespace App\Services\Platform;

use Illuminate\Database\Connection;
use Illuminate\Database\Events\QueryExecuted;
use Illuminate\Support\Facades\DB;

/**
 * Keeps record numbers (ids) identical on the cloud and on a store's on-prem server.
 *
 * 1. Series. Each server generates ids in its own series, STEP apart: the cloud ...001, on-prem slot s ...(s+1).
 *    Two servers can then never give the same id to different records. It is a per-session MariaDB setting
 *    (auto_increment_increment / auto_increment_offset), so it needs nothing server-wide.
 * 2. Tape. A write is copied to the other side by replaying its request there. The source records the id of every
 *    row it inserts (the tape); the replay reuses those ids, so the copy is the same record on both sides.
 *
 * One instance per request (scoped). Only MariaDB/MySQL can do this; on other drivers it stays idle.
 */
class SyncIds
{
    public const STEP = 1000;

    /** Each server's own bookkeeping: never recorded, never forced. */
    private const LOCAL_TABLES = ['sync_outbox', 'personal_access_tokens', 'pos_checkout_requests', 'cache', 'cache_locks', 'jobs',
        'job_batches', 'failed_jobs', 'sessions', 'migrations', 'store_local_nodes', 'platform_activations', 'audit_logs'];

    private bool $recording = false;

    /** @var array<string, list<int>> first id generated by each plain INSERT, per table, in order */
    private array $tape = [];

    /** @var array<string, list<int>>|null ids to reuse on this replay, per table */
    private ?array $playing = null;

    private int $playStep = self::STEP;

    private bool $restorePending = false;

    /** @var array<string, true> tables where this replay and the source did not insert the same rows */
    private array $drift = [];

    /** This connection's own series offset (0 = numbering as usual, no series). */
    private ?int $offset = null;

    private bool $seriesApplied = false;

    // ── Series ──────────────────────────────────────────────────────────────

    /** The offset this install numbers with: on-prem slot + 1, the cloud 1 once it has an on-prem server, else 0. */
    public function seriesOffset(?Connection $connection = null): int
    {
        if ($this->offset !== null) {
            return $this->offset;
        }
        $connection ??= DB::connection();
        if (! $this->supported($connection)) {
            return $this->offset = 0;
        }
        $file = self::settingsFile($connection);
        $saved = is_file($file) ? json_decode((string) @file_get_contents($file), true) : null;
        if (is_array($saved) && isset($saved['offset']) && ($saved['role'] ?? null) === config('sync.node_role')) {
            return $this->offset = (int) $saved['offset'];
        }
        try {
            $rows = $connection->getPdo()->query('select id_slot, enabled from store_local_nodes where id_slot is not null')->fetchAll(\PDO::FETCH_ASSOC);
        } catch (\Throwable) {
            return $this->offset = 0; // Before the migration has run.
        }
        if (config('sync.node_role') === 'local') {
            $own = collect($rows)->firstWhere('enabled', 1) ?? collect($rows)->first();
            $offset = $own ? (int) $own['id_slot'] + 1 : 0;
        } else {
            $offset = $rows ? 1 : 0;
        }
        @file_put_contents($file, json_encode(['offset' => $offset, 'role' => config('sync.node_role')]));

        return $this->offset = $offset;
    }

    /** After a slot is assigned or removed: read it again (and apply it to this request's connection). */
    public function refreshSeries(): void
    {
        $connection = DB::connection();
        @unlink(self::settingsFile($connection));
        $this->offset = null;
        $this->seriesApplied = true;
        $this->applySeries($connection);
    }

    public function applySeries(Connection $connection): void
    {
        $offset = $this->seriesOffset($connection);
        if ($offset > 0) {
            $this->run($connection, 'SET SESSION auto_increment_increment='.self::STEP.', auto_increment_offset='.$offset);
        }
    }

    public function seriesActive(): bool
    {
        return $this->seriesOffset() > 0;
    }

    /** Only MariaDB/MySQL have per-session series and SET INSERT_ID. */
    protected function supported(Connection $connection): bool
    {
        return in_array($connection->getDriverName(), ['mysql', 'mariadb'], true);
    }

    protected function run(Connection $connection, string $sql): void
    {
        $connection->getPdo()->exec($sql);
    }

    protected function generatedId(Connection $connection): int
    {
        return (int) $connection->getPdo()->lastInsertId();
    }

    private static function settingsFile(Connection $connection): string
    {
        // Several installs can share one code folder (a cloud and an on-prem copy); each database has its own file.
        return storage_path('app/sync-ids-'.substr(md5($connection->getDatabaseName().'|'.config('sync.node_role')), 0, 12).'.json');
    }

    // ── Tape: recording at the source ───────────────────────────────────────

    public function startRecording(): void
    {
        $this->recording = true;
        $this->tape = [];
    }

    /** @return array{step: int, ids: array<string, list<int>>}|null what a replay needs to reuse this request's ids */
    public function recorded(): ?array
    {
        return $this->recording && $this->tape && $this->seriesActive() ? ['step' => self::STEP, 'ids' => $this->tape] : null;
    }

    public function afterQuery(QueryExecuted $query): void
    {
        if ($this->restorePending) {
            $this->restoreSeries($query->connection);
        }
        if (! $this->recording || ! ($table = self::plainInsertTable($query->sql))) {
            return;
        }
        try {
            $id = $this->generatedId($query->connection); // Per statement: 0 when it generated none.
        } catch (\Throwable) {
            return;
        }
        if ($id > 0) {
            $this->tape[$table][] = $id;
        }
    }

    // ── Tape: reusing the ids on a replay ───────────────────────────────────

    /** Only called for a replay that proved node trust (AuthenticateSyncReplay). */
    public function play(mixed $tape): void
    {
        if (! is_array($tape) || ! is_array($tape['ids'] ?? null) || ! $this->seriesActive()) {
            return;
        }
        $this->playStep = max(1, (int) ($tape['step'] ?? self::STEP));
        $this->playing = [];
        foreach ($tape['ids'] as $table => $ids) {
            if (is_string($table) && preg_match('/^\w+$/', $table) && is_array($ids) && ! in_array($table, self::LOCAL_TABLES, true)) {
                $this->playing[$table] = array_values(array_filter(array_map('intval', $ids), fn ($id) => $id > 0));
            }
        }
    }

    public function beforeQuery(string $sql, Connection $connection): void
    {
        if (! $this->seriesApplied) {
            $this->seriesApplied = true; // Once per request, before its first statement.
            $this->applySeries($connection);
        }
        if ($this->restorePending) {
            $this->restoreSeries($connection); // The statement before this one failed, so afterQuery never ran.
        }
        if ($this->playing === null || ! ($table = self::plainInsertTable($sql))) {
            return;
        }
        if (empty($this->playing[$table])) {
            $this->drift[$table] = true; // This side inserts a row the source did not: it gets a local id.

            return;
        }
        $id = array_shift($this->playing[$table]);
        // The source's series for this one statement, so the rows of a multi-row insert follow the same numbers.
        $this->run($connection, 'SET SESSION auto_increment_increment='.$this->playStep.', auto_increment_offset='.(($id % $this->playStep) ?: $this->playStep));
        $this->run($connection, 'SET INSERT_ID='.$id);
        $this->restorePending = true;
    }

    /** @return list<string> tables where this replay's rows could not all take the source's ids */
    public function drift(): array
    {
        if ($this->playing === null) {
            return [];
        }
        foreach ($this->playing as $table => $left) {
            if ($left) {
                $this->drift[$table] = true; // The source inserted rows this side did not.
            }
        }

        return array_keys($this->drift);
    }

    private function restoreSeries(Connection $connection): void
    {
        $this->restorePending = false;
        $offset = $this->seriesOffset($connection);
        $this->run($connection, 'SET SESSION auto_increment_increment='.($offset > 0 ? self::STEP : 1).', auto_increment_offset='.max(1, $offset));
    }

    /** The table of a plain INSERT. Upserts and INSERT IGNORE find their row by a natural key and are left alone. */
    public static function plainInsertTable(string $sql): ?string
    {
        if (! preg_match('/^\s*insert\s+into\s+[`"]?(\w+)[`"]?/i', $sql, $match) || stripos($sql, 'on duplicate key') !== false
            || stripos($sql, 'on conflict') !== false) {
            return null;
        }

        return in_array($match[1], self::LOCAL_TABLES, true) ? null : $match[1];
    }

    // ── Floors for a new on-prem server ─────────────────────────────────────

    /** @return array<string, int> the next id of every table here, for an on-prem server to start above */
    public function floors(): array
    {
        $connection = DB::connection();
        if (! $this->supported($connection)) {
            return [];
        }

        return collect($connection->select('select table_name as t, auto_increment as n from information_schema.tables where table_schema = database() and auto_increment is not null'))
            ->filter(fn ($row) => ! in_array($row->t, self::LOCAL_TABLES, true))
            ->mapWithKeys(fn ($row) => [$row->t => (int) $row->n])->all();
    }

    /** Raises this server's counters above the cloud's, so its new ids can't equal an older cloud id of another store. */
    public function raiseAbove(mixed $floors): int
    {
        $connection = DB::connection();
        if (! is_array($floors) || ! $this->supported($connection)) {
            return 0;
        }
        $own = $this->floors();
        $raised = 0;
        foreach ($floors as $table => $floor) {
            if (is_string($table) && preg_match('/^\w+$/', $table) && isset($own[$table]) && (int) $floor > $own[$table]) {
                $this->run($connection, 'ALTER TABLE `'.$table.'` AUTO_INCREMENT = '.(int) $floor);
                $raised++;
            }
        }

        return $raised;
    }
}
